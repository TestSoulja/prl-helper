/**
 * Флаги новых блоков 0.9.0.
 *
 * Отключение — не откат: код остаётся, но блок не создаётся вовсе. Поэтому
 * проверка стоит первой строкой в блоке или в его рендере: выключенный блок
 * не читает данные и не пишет их. Серий, очков и счётчиков это не добавляет.
 *
 * Под флаги не попадают: 112, кризис-карточка, строка «это не лечение»
 * и экран контактов целиком. Они работают всегда, чем бы ни были выключены
 * остальные блоки.
 *
 * Выключить флаг — правка `true` на `false` и новая версия `app/`:
 * на телефоне код обновляется только вместе с `VERSION` в `sw.js`.
 * Неизвестное имя — ошибка, а не «наверное, выключено»: опечатка в имени
 * иначе молча включила бы то, что хотели спрятать.
 */
export const FEATURES = {
  // 4.1 — навык «Одно маленькое дело» и его место в ветке «Пустота»
  oneThing: true,
  // 4.3 — блок «как спалось» в дневнике
  sleepHistory: true,
  // 4.4 — «Пройти план» шагами
  cardPlan: true,
  // 4.4 — необязательное поле «что убрать подальше»
  cardAway: true,
  // 4.4 — первая строка «кому я могу позвонить» крупно
  cardFirst: true,
  // 4.5 — вариант «про себя» внутри «Импульса»
  urgeSelf: true,
  // 4.6 — три новые готовые фразы близким
  messagesExtra: true,
  // 4.7 — блок «если звонить некому»
  noOne: true,
  // 4.8 — блок «первый шаг к врачу»
  firstStep: true,
  // 4.9 — текст про пик паники
  panicNote: true,
  // 4.10 — ожидания и границы на экране приёма
  medsExpect: true,
};

export function featureOn(name) {
  if (!Object.prototype.hasOwnProperty.call(FEATURES, name)) {
    throw new Error(`неизвестный флаг: ${name}`);
  }
  return FEATURES[name] === true;
}
